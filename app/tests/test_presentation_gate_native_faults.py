"""Wrong HOST serialization with a real native producer must never be delivered.

Faults are synthetic. Receipts are generated by the actual isolated kernel;
these are software development tests, not fabricated model answers or benchmarks.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

import pytest


@pytest.mark.parametrize('field,value', [
    ('answer', 'x = 999'),
    ('proof', {}),
    ('scope', 'Verified external world fact'),
    ('world_truth_verified', True),
])
def test_real_native_receipts_cannot_authorize_false_presentation(field, value):
    bundle = Path(os.environ['HOSTED_TEST_COMPETITION_BUNDLE'])
    manifest = bundle / 'hosted-test-manifest.json'
    pin = hashlib.sha256(manifest.read_bytes()).hexdigest()
    code = '''
import json, sys
from hosted_judge import provisional_math_presentation as presentation
from hosted_judge.native_adapter import execute_native
original = presentation.provisional_math
seen = []
def inject(api, selection, summary, checkpoint, policy):
    shown = original(api, selection, summary, checkpoint, policy)
    assert len(summary['receipts']) == 2
    assert all(r['verification']['passed'] for r in summary['receipts'])
    seen.append(len(summary['receipts']))
    shown[sys.argv[4]] = json.loads(sys.argv[5])
    return shown
presentation.provisional_math = inject
try:
    execute_native(sys.argv[1], sys.argv[2], sys.argv[3],
        'Solve 3x=9 for integer x between 0 and 9.', None, 'a'*32, 'b'*32)
except ValueError as error:
    assert str(error).startswith('PRESENTATION_'), str(error)
    assert seen == [2]
    print(json.dumps({'status':'REJECTED_BEFORE_DELIVERY',
        'actual_native_receipts':2, 'provider_calls':0, 'error':str(error)}))
else:
    raise AssertionError('False mathematical presentation was delivered')
'''
    result = subprocess.run(
        [sys.executable, '-B', '-c', code, str(bundle), str(manifest), pin,
         field, json.dumps(value)], capture_output=True, text=True,
        timeout=20, check=False)
    assert result.returncode == 0, result.stderr
    actual = json.loads(result.stdout)
    assert actual['status'] == 'REJECTED_BEFORE_DELIVERY'
    assert actual['actual_native_receipts'] == 2 and actual['provider_calls'] == 0
